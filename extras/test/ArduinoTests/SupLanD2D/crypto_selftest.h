#ifndef EXTRAS_TEST_ARDUINOTESTS_SUPLAND2D_CRYPTO_SELFTEST_H_
#define EXTRAS_TEST_ARDUINOTESTS_SUPLAND2D_CRYPTO_SELFTEST_H_

#include <supla/crypto.h>
#include <supla/sha256.h>

// Independent SHA/HMAC and cryptography AESCCM known-answer fixtures.
inline bool cryptoSelfTest(Supla::SupLan::CryptoPort *crypto) {
  const uint8_t key[16] = {
      0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
      0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
  const uint8_t nonce[12] = {
      0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
      0x08, 0x09, 0x0a, 0x0b};
  const uint8_t aad[7] = {
      0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06};
  const uint8_t plain[17] = {
      0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
      0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
      0x10};
  const uint8_t expected[33] = {
      0x33, 0x14, 0xf1, 0x64, 0xd8, 0x85, 0xc2, 0xb6,
      0x79, 0x1a, 0xc3, 0xeb, 0x0e, 0xe7, 0x8b, 0x8f,
      0x7c, 0x5d, 0xf3, 0xd8, 0x07, 0x02, 0x2d, 0x01,
      0x0f, 0x3d, 0xec, 0x76, 0x19, 0x4b, 0x98, 0x50,
      0x10};
  const uint8_t emptyTag[16] = {
      0xd8, 0x59, 0x88, 0x74, 0x4b, 0x16, 0x00, 0xab,
      0x97, 0x5a, 0x29, 0x8a, 0xef, 0xc9, 0x41, 0x46};
  const uint8_t sha[32] = {
      0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea,
      0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22, 0x23,
      0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c,
      0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad};
  const uint8_t mac[32] = {
      0xd6, 0x01, 0xcc, 0x17, 0x75, 0x59, 0xb0, 0x24,
      0x84, 0x59, 0x78, 0x7f, 0x7e, 0x80, 0x4e, 0xd7,
      0xf2, 0x76, 0x89, 0xb5, 0x99, 0x5c, 0x59, 0xb6,
      0x61, 0x80, 0x2d, 0x96, 0x82, 0xfd, 0xf8, 0xd2};
  const uint8_t abc[] = {'a', 'b', 'c'};
  uint8_t digest[32] = {};
  uint8_t cipher[17] = {};
  uint8_t tag[16] = {};
  uint8_t decoded[17] = {};
  bool valid = Supla::Sha256::calculate(abc, sizeof(abc), digest) &&
      memcmp(digest, sha, 32) == 0 &&
      Supla::Crypto::hmacSha256(key, sizeof(key), abc, sizeof(abc), digest) &&
      memcmp(digest, mac, 32) == 0 &&
      crypto->aes128CcmEncrypt(key, nonce, aad, sizeof(aad), plain,
                              sizeof(plain), cipher, tag) &&
      memcmp(cipher, expected, sizeof(cipher)) == 0 &&
      memcmp(tag, expected + sizeof(cipher), sizeof(tag)) == 0 &&
      crypto->aes128CcmDecrypt(key, nonce, aad, sizeof(aad), cipher,
                              sizeof(cipher), tag, decoded) &&
      memcmp(decoded, plain, sizeof(plain)) == 0;
  tag[0] ^= 1;
  valid = valid && !crypto->aes128CcmDecrypt(
      key, nonce, aad, sizeof(aad), cipher, sizeof(cipher), tag, decoded);
  for (const auto byte : decoded) {
    valid = valid && byte == 0;
  }
  valid = valid && crypto->aes128CcmEncrypt(
      key, nonce, aad, sizeof(aad), nullptr, 0, nullptr, tag) &&
      memcmp(tag, emptyTag, sizeof(tag)) == 0 &&
      crypto->aes128CcmDecrypt(key, nonce, aad, sizeof(aad), nullptr, 0,
                              tag, nullptr);
  return valid;
}

#endif  // EXTRAS_TEST_ARDUINOTESTS_SUPLAND2D_CRYPTO_SELFTEST_H_
