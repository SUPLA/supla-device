int fontIndex(char value) {
  if (value == ' ') {
    return 0;
  }
  if (value >= '0' && value <= '9') {
    return 1 + value - '0';
  }
  if (value >= 'a' && value <= 'z') {
    value = value - 'a' + 'A';
  }
  if (value >= 'A' && value <= 'Z') {
    return 11 + value - 'A';
  }
  switch (value) {
    case '-':
      return 37;
    case '.':
      return 38;
    case ':':
      return 39;
    case '?':
      return 40;
    case '+':
      return 41;
    case '/':
      return 42;
    case '!':
      return 43;
    case '~':
      return 44;
    case '\'':
      return 45;
    case ')':
      return 46;
    case static_cast<char>(0xB0):
      return 47;
    default:
      return 0;
  }
}
